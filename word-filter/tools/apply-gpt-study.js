function apply(file, changes) {
	const full = path.join(LISTS, file);
	const doc = JSON.parse(fs.readFileSync(full, 'utf8'));
	let n = 0;
	for (const [id, [pattern, why]] of Object.entries(changes)) {
		const e = doc.entries.find((x) => x.id === id);
		if (!e) throw new Error('אין רשומה ' + id);
		if (e.pattern === pattern) continue;
		if (!e.original) e.original = e.pattern;
		e.pattern = pattern;
		e.note = (e.note ? e.note + ' ' : '') + NOTE + ': ' + why + '.';
		n++;
	}
	fs.writeFileSync(full, JSON.stringify(doc, null, '\t') + '\n');
	console.log(file + ':', n, 'עודכנו');
}
apply('words.json', WORDS);
apply('allow.json', ALLOW);
