const list = JSON.parse(fs.readFileSync(file, 'utf8'));
const byId = Object.fromEntries(list.entries.map((e) => [e.id, e]));
let merged = 0, changed = 0;
for (const [main, others, pattern, extra, note] of GROUPS.concat(FAMILIES)) {
	const m = byId[main];
	if (!m) throw new Error('אין רשומה ' + main);
	if (m.status === 'merged') continue; // ראשית משלב 1 שאוחדה בשלב 2 (הרצה חוזרת)
	for (const id of others) {
		const o = byId[id];
		if (!o) throw new Error('אין רשומה ' + id);
		if (o.status === 'merged') continue;
		if (o.topic !== m.topic && !CROSS_TOPIC.includes(id)) throw new Error(`נושא שונה: ${id} ${o.topic} / ${main} ${m.topic}`);
		if (FAMILIES.some((f) => f[0] === main) && (o.status !== m.status || o.level !== m.level))
			throw new Error(`רמה או סטטוס שונים: ${id} ${o.level}/${o.status} - ${main} ${m.level}/${m.status}`);
		// רשומה שכבר ראשית של קבוצה אחרת - הילדים שלה עוברים לראשית החדשה.
		for (const c of list.entries) if (c.mergedInto === id) c.mergedInto = main;
		for (const s of o.sources || []) if (!(m.sources || []).includes(s)) (m.sources = m.sources || []).push(s);
		if (o.status === 'active') m.status = 'active';
		o.status = 'merged';
		o.mergedInto = main;
		merged++;
	}
	// תבנית שנקבעת שוב בשלב 2 (משפחה) - שם היא נקבעת.
	const later = FAMILIES.find((f) => f[0] === main && f[2]);
	if (pattern && pattern !== m.pattern && !(later && later[2] !== pattern)) {
		if (!m.original) m.original = m.pattern;
		m.pattern = pattern;
		changed++;
	}
	Object.assign(m, extra);
	if (!(m.sources || []).includes(NOTE)) (m.sources = m.sources || []).push(NOTE);
	if (note === null) { // שלב 3: ההסבר הקיים נשאר, ומתווסף מה שנבלע
		const added = others.filter((id) => !(m.mergeNote || '').includes(id));
		if (added.length) m.mergeNote = ((m.mergeNote || '') + ' נבלעו (כל ההתאמות שלהן כבר נתפסו כאן): ' + added.join(', ') + '.').trim();
		continue;
	}
	m.mergeNote = note + (others.length ? ' אוחדו: ' + others.join(', ') + '.' : '');
}
fs.writeFileSync(file, JSON.stringify(list, null, '\t') + '\n');
console.log(`אוחדו ${merged} רשומות ל-${GROUPS.length + FAMILIES.length} קבוצות; ${changed} תבניות עודכנו.`);
