// הצבעה: כל קטגוריה (או החלק שאחרי ה-":") לנושא אחד; תבנית המידע - קול כפול.
function subjectOf(cats, ib, stubs) {
	const votes = new Map();
	const vote = (code, w) => votes.set(code, (votes.get(code) || 0) + w);
	for (const raw of cats) {
		if (NOISE_CAT.test(raw)) continue;
		const c = raw.includes(': ') ? raw.split(': ').pop() : raw;
		const hit = SUBJECTS.find(([, re]) => re.test(c)) || SUBJECTS.find(([, re]) => re.test(raw));
		if (hit) vote(hit[0], 1);
	}
	for (const [code, , ibRe] of SUBJECTS) if (ibRe && ib && ibRe.test(ib)) vote(code, 2);
	for (const st of stubs || []) { const t = stubTopic(st); if (t && !t.startsWith('people_') && t !== 'sensitive') vote(t, 2); }
	let best = null, bestN = 0;
	for (const [code] of SUBJECTS) {
		const n = votes.get(code) || 0;
		if (n > bestN) { best = code; bestN = n; }
	}
	return best;
}

