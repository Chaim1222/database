// page = {t: כותרת, ib: תבנית המידע, cats: [קטגוריות], disamb: האם דף פירושונים, dict: הסימון המילוני}
function classify(page) {
	const cats = page.cats || [], ib = page.ib || '', title = page.t || '';
	const cat = (re) => cats.some((c) => re.test(c));
	if (page.disamb || ib === 'פירושונים') return 'disambig';
	if (YEAR_TITLE.test(title)) return 'years';
	if (/^רשימ(ת|ות) /.test(title)) return 'lists';
	if (page.dict) return 'dictionary';
	if (cat(SENSITIVE)) return 'sensitive';
	if (ib === 'מיון') return 'nature';
	if (ib === 'יצירת אמנות' || cat(ART)) return 'art';
	if (PERSON_IB.test(ib) || cat(PERSON_CAT)) {
		for (const [code, re] of PEOPLE) if (cat(re)) return code;
		for (const [code, re] of PEOPLE_IB) if (re.test(ib)) return code;
		return 'people_other';
	}
	for (const [code, re, ibRe] of SUBJECTS) if (ibRe.test(ib) || cat(re)) return code;
	return 'other';
}

const DISAMBIG = /\{\{\s*(פירושונים|פירוש|disambig)\s*[|}]/i;

function topicOf(text, title) {
	text = text || '';
	return classify({ t: title, ib: infoboxOf(text), cats: categoriesOf(text), disamb: DISAMBIG.test(text), dict: dictionaryOf(text) });
}

