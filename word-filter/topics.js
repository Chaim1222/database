const NOT_TOPIC_INFOBOX = /^(הערה|הערות שוליים|קישור (כללי|שפה)|ציטוט|אנ|ה|צ-.*|משמאל לימין|אין לבלבל עם|לערוך|תצוגת שם|ynet|הארץ|Cite.*|cite.*|Citation|Sfn|sfn|Harvnb|in lang|ביאור|חלונית|גר|ערך מורחב|הפניה לערך מורחב|תמונה רחבה|יפא|ויקיטקסט.*|ציטוטון|אחר|אתר רשמי|יוטיוב|!|מסת"ב|למנויים|ישראל היום|מעריב|גלובס|כלכליסט|וואלה|N12|mako|דבר|ידיעות.*|הקישור.*)$/;
function topicInfoboxOf(text) {
	const found = (text || '').replace(/<!--[\s\S]*?-->/g, '').match(/\{\{\s*([^|}\n]+?)\s*(?:\n|\||\}\})/g) || [];
	for (const raw of found) {
		const name = raw.replace(/^\{\{\s*/, '').replace(/\s*(\n|\||\}\})$/, '').trim();
		if (name.includes(':') || NOT_TOPIC_INFOBOX.test(name)) continue;
		if (/^(פירוש נוסף|לשכתב|עריכה|שכתוב|מקורות|אין מקורות|ערך מחפש מקורות|הבהרה|דגל|DISPLAYTITLE|לא לבלבל|בעבודה|קצרמר|שם|סימן|מיזוג|ערך מחקרי|מקור|להשלים|רשימה|ללא|לפצל|עדכון|חסר)/.test(name)) continue;
		return name;
	}
	return null;
}

