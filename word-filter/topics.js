function topicFromDescription(desc) {
	const d = (desc || '').replace(/\s*\(מתוך הפתיח\)\s*$/, '').trim();
	if (!d) return null;
	const hit = DESC_RULES.find(([, re]) => re.test(d));
	return hit ? hit[0] : null;
}
