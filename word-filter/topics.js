const OCC_START = PEOPLE.map(([, re]) => new RegExp('^(' + re.source.replace(/^\(|\)$/g, '') + ')'));
const NOT_OCC = /^(נסיכות|חסידות|פסלים ב|פסלי |מלכות |רוזנות|דוכסיות|מחברי |כותבי |אמני .*(רקורדס|Records))/;
