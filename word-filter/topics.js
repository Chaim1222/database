function stubsOf(text) {
	const out = [];
	for (const m of (text || '').matchAll(/\{\{\s*קצרמר\s*((?:\|[^{}]*)?)\}\}/g)) {
		for (const part of m[1].split('|').slice(1)) {
			const v = part.replace(/^\s*(נושא נוסף|מידע נוסף)\s*=/, (x, k) => (k === 'נושא נוסף' ? '' : '\u0000')).trim();
			if (v && !v.startsWith('\u0000') && !/=/.test(v)) out.push(v);
		}
	}
	return out;
}

