# ב-(?:...) כדי לבודד אותה בתוך ה-alternation.
_COMBINED_PATTERN = "|".join(f"(?:{p})" for p in PATTERNS)
COMBINED_RE = re.compile(_COMBINED_PATTERN)


def is_clean_of_problematic_words(content):
    """
    True אם התוכן *נקי* - אף תבנית לא נמצאה בו (מתאים ישירות לעמודה
    problematic_words_clean). False אם נמצאה התאמה של תבנית אחת
    לפחות, בכל מקום בתוכן.
    """
    return COMBINED_RE.search(content) is None
